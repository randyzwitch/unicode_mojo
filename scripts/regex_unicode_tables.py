"""Write unicode_mojo/_regex_tables.mojo: the code point sets behind the
regex engine's Unicode \\w, \\d and \\s, and its simple case-folding orbits.

The generator tests every scalar value against `^\\w$`, `^\\d$` and `^\\s$`,
and every code point with a case mapping against `(?i)^\\x{...}$`. Matching
code points are compressed into range sets, preserving the Unicode behavior
of the generated tables. Run it in the oracle environment:

    python3 scripts/regex_unicode_tables.py  # requires Polars 1.44.2

Use --from-fixtures to reproduce the frozen constructors without Polars.
Add --check to compare with the committed, formatted module without writing.
"""
from pathlib import Path

import argparse
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "unicode_mojo" / "_regex_tables.mojo"


def ranges(members: list[int]) -> list[list[int]]:
    out: list[list[int]] = []
    for c in members:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def numeric_constructor(name: str, values: list[int]) -> str:
    lines = [
        "def %s() -> List[UInt32]:" % name,
        "    var values = List[UInt32](unsafe_uninit_length=%d)" % len(values),
        "    var data = values.unsafe_ptr()",
    ]
    # Every scalar slot is initialized before the owned list is returned.
    lines.extend("    data[unsafe_offset=%d] = 0x%X" % (i, cp) for i, cp in enumerate(values))
    lines.append("    return values^")
    return "\n".join(lines)


def render(
    sets: dict[str, list[list[int]]], pairs: list[tuple[int, int]], version: str
) -> str:
    text = [
        '"""Unicode tables for the regex engine, generated by',
        "scripts/regex_unicode_tables.py from Polars %s (Rust `regex`)."
        % version,
        "",
        "Range constructors return flat lists of inclusive endpoint pairs.",
        "Folding keys map each code point with a simple case folding to the next",
        'member of its folding orbit (`k` -> `K` -> KELVIN SIGN -> `k`)."""',
        "",
    ]
    for name in ("WORD", "DIGIT", "SPACE"):
        values = [cp for pair in sets[name] for cp in pair]
        text.append("\n" + numeric_constructor(name.lower() + "_ranges", values) + "\n")
    text.append("\n" + numeric_constructor("fold_keys", [a for a, _ in pairs]) + "\n")
    text.append("\n" + numeric_constructor("fold_next", [b for _, b in pairs]))
    return "\n".join(text) + "\n"


def write_or_check(text: str, check: bool) -> None:
    with tempfile.TemporaryDirectory() as directory:
        temporary = Path(directory) / OUT.name
        temporary.write_text(text)
        subprocess.run(
            ["mblack", "--target-version", "mojo", "--line-length", "80", str(temporary)],
            check=True,
        )
        formatted = temporary.read_text()
    if check:
        if OUT.read_text() != formatted:
            raise SystemExit("Generated regex tables differ from the committed module")
        print("Frozen regex range and folding constructors match")
    else:
        OUT.write_text(formatted)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-fixtures", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.from_fixtures:
        sets = {}
        for line in (ROOT / "tests/fixtures/unicode_perl_ranges.tsv").read_text().splitlines():
            name, raw = line.split("\t")
            pairs = [token.split("-") for token in raw.split()]
            sets[name] = [[int(pair[0], 16), int(pair[-1], 16)] for pair in pairs]
        folds = [tuple(int(value, 16) for value in line.split("\t")) for line in
                 (ROOT / "tests/fixtures/unicode_folding.tsv").read_text().splitlines()]
        assert set(sets) == {"WORD", "DIGIT", "SPACE"}
        assert len(folds) == 2884
        write_or_check(render(sets, folds, "1.44.2"), args.check)
        return

    import polars as pl

    if pl.__version__ != "1.44.2":
        raise SystemExit("Oracle regeneration requires Polars 1.44.2")
    cps = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]
    column = pl.Series("s", [chr(c) for c in cps])
    sets = {}
    for name, pattern in (("WORD", r"^\w$"), ("DIGIT", r"^\d$"), ("SPACE", r"^\s$")):
        hits = column.str.contains(pattern).to_list()
        sets[name] = ranges([c for c, hit in zip(cps, hits) if hit])

    candidates = set()
    for c in cps:
        for mapped in (chr(c).lower(), chr(c).upper(), chr(c).casefold(), chr(c).title()):
            if mapped != chr(c):
                candidates.add(c)
                if len(mapped) == 1:
                    candidates.add(ord(mapped))
    candidates = sorted(candidates)
    cased = pl.Series("s", [chr(c) for c in candidates])
    orbits: dict[int, list[int]] = {}
    for c in candidates:
        hits = cased.str.contains("(?i)^\\x{%X}$" % c).to_list()
        orbit = [x for x, hit in zip(candidates, hits) if hit]
        if len(orbit) > 1:
            orbits[c] = orbit
    # Nothing outside the candidates may fold onto one of them.
    folded = "(?i)^[" + "".join("\\x{%X}" % c for c in orbits) + "]$"
    hits = column.str.contains(folded).to_list()
    stray = [c for c, hit in zip(cps, hits) if hit and c not in orbits]
    assert not stray, stray
    pairs = []
    for c, orbit in sorted(orbits.items()):
        assert orbits[orbit[0]] == orbit
        pairs.append((c, orbit[(orbit.index(c) + 1) % len(orbit)]))

    write_or_check(render(sets, pairs, pl.__version__), args.check)


if __name__ == "__main__":
    main()
